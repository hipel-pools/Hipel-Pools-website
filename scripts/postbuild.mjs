// Post-build step: makes each output folder a complete, deploy-ready static site.
//   node scripts/postbuild.mjs <outDir> <main|blog>
// Writes: sitemap.xml, robots.txt, _redirects, _headers. Fixes the one trailing-slash URL.
import fs from 'node:fs';
import path from 'node:path';

const [outDir, target] = process.argv.slice(2);
const root = path.resolve(outDir);
const site = JSON.parse(fs.readFileSync('src/data/site.json', 'utf8'));
const host = target === 'blog' ? site.blogHost : site.mainHost;
const otherHost = target === 'blog' ? site.mainHost : site.blogHost;
const redirects = JSON.parse(fs.readFileSync('src/data/redirects.json', 'utf8'));
const files = JSON.parse(fs.readFileSync('src/data/images.json', 'utf8'));

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));

// 1. URLs that end in "/" on the old site must be served from a folder index.
const SLASH_PAGES = target === 'main' ? ['/pool-service/pool-closing/'] : [];
for (const p of SLASH_PAGES) {
  const from = path.join(root, p.slice(1, -1) + '.html');
  if (fs.existsSync(from)) {
    fs.mkdirSync(path.join(root, p.slice(1)), { recursive: true });
    fs.renameSync(from, path.join(root, p.slice(1), 'index.html'));
  }
}

// 2. Main build doesn't need blog feeds; blog build doesn't need the 230 MB of /files (served from the main site).
if (target === 'main') {
  for (const f of ['rss.xml', 'academy/rss.xml']) fs.rmSync(path.join(root, f), { force: true });
  fs.rmSync(path.join(root, 'academy'), { recursive: true, force: true });
} else {
  fs.rmSync(path.join(root, 'files'), { recursive: true, force: true });
}

// 3. sitemap.xml – every built page except 404 / noindex pages
const pages = walk(root).filter((f) => f.endsWith('.html') && !f.endsWith('404.html'));
const urls = pages
  .filter((f) => !/name="robots" content="[^"]*noindex/.test(fs.readFileSync(f, 'utf8')))
  .map((f) => {
    let rel = path.relative(root, f).replace(/\\/g, '/');
    if (rel === 'index.html') return host;
    if (rel.endsWith('/index.html')) return `${host}/${rel.slice(0, -'index.html'.length)}`;
    return `${host}/${rel.replace(/\.html$/, '')}`;
  })
  // listing pagination duplicates (/page/1) are not sitemap material
  .filter((u) => !u.endsWith('/page/1'))
  .sort();
fs.writeFileSync(
  path.join(root, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    urls.map((u) => `  <url><loc>${u.replace(/&/g, '&amp;')}</loc></url>`).join('\n') +
    '\n</urlset>\n'
);

// 4. robots.txt
const preview = Boolean(process.env.SITE_MAIN_URL || process.env.SITE_BLOG_URL);
fs.writeFileSync(path.join(root, 'robots.txt'), preview
  ? 'User-agent: *\nDisallow: /\n'
  : `User-agent: *\nDisallow: /api/\n\nSitemap: ${host}/sitemap.xml\n`);

// 5. _redirects (Cloudflare Pages / Netlify format). Exact-match rules, 301.
const lines = ['# Generated by scripts/postbuild.mjs – redirects carried over from HubSpot + old file URLs'];
const seen = new Set();
const add = (from, to) => {
  if (!from || from === to || seen.has(from) || /\s/.test(from)) return;
  seen.add(from);
  lines.push(`${from} ${to} 301`);
};
for (const r of redirects) {
  const from = new URL(r.from);
  if (from.origin !== host) continue;
  const to = new URL(r.to);
  add(from.pathname, to.origin === host ? to.pathname : to.href);
}
// Old HubSpot file URLs (images/PDFs indexed by Google or linked from other sites) -> new /files/ paths
for (const [src, local] of Object.entries(files)) {
  const u = new URL(src);
  if (u.hostname !== 'hipelpools.ca') continue;
  const to = target === 'main' ? local : site.mainHost + local;
  add(u.pathname, to);
  add(u.pathname.replace('/hubfs/', '/hs-fs/hubfs/'), to);
}
// HubSpot's trailing-slash behaviour for pages: /page/ -> /page
lines.push('/en-ca/request-a-quote/ /en-ca/request-a-quote 301');
lines.push('/pool-service/pool-closing /pool-service/pool-closing/ 301');
fs.writeFileSync(path.join(root, '_redirects'), lines.join('\n') + '\n');

// 6. _headers: long cache for fingerprinted assets, sensible security headers
fs.writeFileSync(
  path.join(root, '_headers'),
  `/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin\n  X-Frame-Options: SAMEORIGIN\n` +
    // Cloudflare preview addresses (*.pages.dev) are never indexed, even after launch
    `https://:project.pages.dev/*\n  X-Robots-Tag: noindex\n` +
    `https://:version.:project.pages.dev/*\n  X-Robots-Tag: noindex\n` +
    `/_astro/*\n  Cache-Control: public, max-age=31536000, immutable\n` +
    (target === 'main' ? `/files/*\n  Cache-Control: public, max-age=2592000\n` : '')
);

console.log(`[postbuild] ${target}: ${urls.length} sitemap URLs, ${lines.length - 1} redirects → ${root}`);
